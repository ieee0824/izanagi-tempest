/// In-memory, process-bound authorization. It is deliberately neither Clone
/// nor serializable; a proof directory by itself is not a launcher permit.
pub struct LaunchPermit {
    envelope: VerifiedEnvelope,
    proof_root: PathBuf,
    code: BTreeMap<String, PathBuf>,
    issued_pid: u32,
    probe_started: Instant,
    staged_code: bool,
    system_files: SystemFiles,
}

/// One-shot, in-memory challenge generated by the trusted probe runner before
/// it starts the measured CLI. Proof files cannot manufacture this value.
pub struct ProbeChallenge {
    probe_id: String,
    nonce: String,
    created_ns: u64,
    started: Instant,
}

impl ProbeChallenge {
    pub fn generate() -> io::Result<Self> {
        Ok(Self {
            probe_id: format!("probe-{}", host_io::random_hex()?),
            nonce: host_io::random_hex()?,
            created_ns: host_io::now_ns()?,
            started: Instant::now(),
        })
    }

    pub fn probe_id(&self) -> &str {
        &self.probe_id
    }

    pub fn nonce(&self) -> &str {
        &self.nonce
    }

    pub(crate) fn nonce_sha256(&self) -> String {
        sha256(self.nonce.as_bytes())
    }
}

impl LaunchPermit {
    pub(crate) fn system_files(&self) -> &SystemFiles {
        &self.system_files
    }

    pub fn profile(&self) -> &LauncherProfile {
        &self.envelope.profile
    }

    pub fn profile_sha256(&self) -> &str {
        &self.envelope.profile_sha256
    }

    pub fn code_path(&self, role: &str) -> io::Result<&Path> {
        self.code
            .get(role)
            .map(PathBuf::as_path)
            .ok_or_else(|| invalid("authorized launcher code role missing"))
    }

    pub fn verify_immediately_before_launch(&self) -> io::Result<()> {
        if self.issued_pid != std::process::id()
            || self.probe_started.elapsed() > Duration::from_secs(60)
        {
            return Err(invalid(
                "launcher permit expired or crossed a process boundary",
            ));
        }
        let current = load_envelope_inner(&self.proof_root, !self.staged_code, &self.system_files)?;
        if current.proof_id != self.envelope.proof_id
            || current.profile_sha256 != self.envelope.profile_sha256
            || current.proof_sha256 != self.envelope.proof_sha256
            || current.runner_sha256 != self.envelope.runner_sha256
            || current.probe_id != self.envelope.probe_id
            || current.probe_nonce_sha256 != self.envelope.probe_nonce_sha256
        {
            return Err(invalid("launcher proof changed after authorization"));
        }
        for artifact in &self.envelope.profile.code_closure {
            let path = self.code_path(&artifact.role)?;
            if host_io::digest(path)? != artifact.sha256 {
                return Err(invalid("authorized launcher copy changed"));
            }
        }
        Ok(())
    }
}

pub fn authorize_launch(
    proof_root: &Path,
    code_destination: &Path,
    challenge: ProbeChallenge,
) -> io::Result<LaunchPermit> {
    authorize_launch_with_system_files(
        proof_root,
        code_destination,
        challenge,
        SystemFiles::default(),
    )
}

fn authorize_launch_with_system_files(
    proof_root: &Path,
    code_destination: &Path,
    challenge: ProbeChallenge,
    system_files: SystemFiles,
) -> io::Result<LaunchPermit> {
    if code_destination.exists() {
        return Err(invalid("launcher code destination already exists"));
    }
    let envelope = load_envelope_inner(proof_root, true, &system_files)?;
    let now = host_io::now_ns()?;
    if challenge.started.elapsed() > Duration::from_secs(60)
        || envelope.created_ns < challenge.created_ns
        || envelope.created_ns > now
        || now - envelope.created_ns > 60_000_000_000
        || envelope.runner_sha256 != host_io::digest(&std::env::current_exe()?)?
        || envelope.probe_id != challenge.probe_id
        || envelope.probe_nonce_sha256 != challenge.nonce_sha256()
    {
        return Err(invalid(
            "capability probe is stale or belongs to another runner",
        ));
    }
    let code = materialize_code(&envelope, code_destination)?;
    let permit = LaunchPermit {
        envelope,
        proof_root: proof_root.canonicalize()?,
        code,
        issued_pid: std::process::id(),
        probe_started: challenge.started,
        staged_code: false,
        system_files,
    };
    permit.verify_immediately_before_launch()?;
    Ok(permit)
}

fn exact_directory(path: &Path, expected: &[&str]) -> io::Result<bool> {
    let metadata = path.symlink_metadata()?;
    if !metadata.is_dir()
        || metadata.uid() != unsafe { libc::geteuid() }
        || metadata.permissions().mode() & 0o077 != 0
    {
        return Ok(false);
    }
    let mut names = fs::read_dir(path)?
        .map(|entry| {
            entry.and_then(|entry| {
                entry
                    .file_name()
                    .into_string()
                    .map_err(|_| invalid("non-UTF-8 staged code entry"))
            })
        })
        .collect::<io::Result<Vec<_>>>()?;
    names.sort();
    Ok(names == expected)
}

/// Authorize code copies staged by the same trusted runner before the
/// challenge clock starts. The exact layout and every byte are revalidated
/// against the challenge-bound profile; no caller-provided path is trusted.
pub(crate) fn authorize_staged_launch(
    proof_root: &Path,
    code_destination: &Path,
    challenge: ProbeChallenge,
) -> io::Result<LaunchPermit> {
    authorize_staged_launch_with_system_files(
        proof_root,
        code_destination,
        challenge,
        SystemFiles::default(),
    )
}

fn authorize_staged_launch_with_system_files(
    proof_root: &Path,
    code_destination: &Path,
    challenge: ProbeChallenge,
    system_files: SystemFiles,
) -> io::Result<LaunchPermit> {
    let envelope = load_envelope_inner(proof_root, false, &system_files)?;
    let now = host_io::now_ns()?;
    if challenge.started.elapsed() > Duration::from_secs(60)
        || envelope.created_ns < challenge.created_ns
        || envelope.created_ns > now
        || now - envelope.created_ns > 60_000_000_000
        || envelope.runner_sha256 != host_io::digest(&std::env::current_exe()?)?
        || envelope.probe_id != challenge.probe_id
        || envelope.probe_nonce_sha256 != challenge.nonce_sha256()
    {
        return Err(invalid(format!(
            "staged capability challenge is invalid after {} ms",
            challenge.started.elapsed().as_millis()
        )));
    }
    if !exact_directory(code_destination, &["host", "jail"])?
        || !exact_directory(&code_destination.join("jail"), &["bin"])?
        || !exact_directory(&code_destination.join("jail/bin"), &["agent", "tempest"])?
        || !exact_directory(&code_destination.join("host"), &["model-api-relay"])?
    {
        return Err(invalid("staged launcher code layout is invalid"));
    }
    let mut code = BTreeMap::new();
    for artifact in &envelope.profile.code_closure {
        let target = match artifact.role.as_str() {
            "agent_executable" => code_destination.join("jail/bin/agent"),
            "mcp_bridge" => code_destination.join("jail/bin/tempest"),
            "model_api_relay" => code_destination.join("host/model-api-relay"),
            _ => return Err(invalid("unsupported staged launcher code role")),
        };
        let metadata = target.symlink_metadata()?;
        if !metadata.is_file()
            || metadata.uid() != unsafe { libc::geteuid() }
            || metadata.permissions().mode() & 0o077 != 0
            || host_io::digest(&target)? != artifact.sha256
        {
            return Err(invalid("staged launcher code digest mismatch"));
        }
        code.insert(artifact.role.clone(), target);
    }
    if code.len() != 3 {
        return Err(invalid("staged launcher code closure is incomplete"));
    }
    Ok(LaunchPermit {
        envelope,
        proof_root: proof_root.canonicalize()?,
        code,
        issued_pid: std::process::id(),
        probe_started: challenge.started,
        staged_code: true,
        system_files,
    })
}

/// Copy measured launcher code into one run-private directory and verify the
/// copies. Launchers must execute these paths, never the original live paths.
pub fn materialize_code(
    proof: &VerifiedEnvelope,
    destination: &Path,
) -> io::Result<BTreeMap<String, PathBuf>> {
    host_io::directory(destination)?;
    host_io::directory(&destination.join("jail"))?;
    host_io::directory(&destination.join("jail/bin"))?;
    host_io::directory(&destination.join("host"))?;
    let mut paths = BTreeMap::new();
    for artifact in &proof.profile.code_closure {
        let target = match artifact.role.as_str() {
            "agent_executable" => destination.join("jail/bin/agent"),
            "mcp_bridge" => destination.join("jail/bin/tempest"),
            "model_api_relay" => destination.join("host/model-api-relay"),
            role => destination.join("host").join(role),
        };
        host_io::private_copy(&artifact.path, &target)?;
        if host_io::digest(&target)? != artifact.sha256 {
            return Err(invalid("copied launcher code digest mismatch"));
        }
        fs::set_permissions(&target, fs::Permissions::from_mode(0o500))?;
        paths.insert(artifact.role.clone(), target);
    }
    Ok(paths)
}

fn invalid(message: impl Into<String>) -> io::Error {
    io::Error::other(message.into())
}

fn digest(value: &str) -> bool {
    value.len() == 64 && value.bytes().all(|byte| byte.is_ascii_hexdigit())
}

fn identifier(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 128
        && value != "."
        && value != ".."
        && value
            .bytes()
            .all(|byte| byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-'))
}

fn bounded(path: &Path) -> io::Result<Vec<u8>> {
    let metadata = path.symlink_metadata()?;
    if !metadata.is_file() || metadata.len() > LIMIT {
        return Err(invalid("proof artifact must be a bounded regular file"));
    }
    fs::read(path)
}

fn sha256(bytes: &[u8]) -> String {
    format!("{:x}", Sha256::digest(bytes))
}

struct UniqueValue(serde_json::Value);

impl<'de> serde::Deserialize<'de> for UniqueValue {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct Visitor;
        impl<'de> serde::de::Visitor<'de> for Visitor {
            type Value = UniqueValue;
            fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                formatter.write_str("JSON without duplicate object keys")
            }
            fn visit_bool<E: serde::de::Error>(self, value: bool) -> Result<Self::Value, E> {
                Ok(UniqueValue(value.into()))
            }
            fn visit_i64<E: serde::de::Error>(self, value: i64) -> Result<Self::Value, E> {
                Ok(UniqueValue(value.into()))
            }
            fn visit_u64<E: serde::de::Error>(self, value: u64) -> Result<Self::Value, E> {
                Ok(UniqueValue(value.into()))
            }
            fn visit_f64<E: serde::de::Error>(self, value: f64) -> Result<Self::Value, E> {
                serde_json::Number::from_f64(value)
                    .map(serde_json::Value::Number)
                    .map(UniqueValue)
                    .ok_or_else(|| E::custom("non-finite JSON number"))
            }
            fn visit_str<E: serde::de::Error>(self, value: &str) -> Result<Self::Value, E> {
                Ok(UniqueValue(value.into()))
            }
            fn visit_string<E: serde::de::Error>(self, value: String) -> Result<Self::Value, E> {
                Ok(UniqueValue(value.into()))
            }
            fn visit_none<E: serde::de::Error>(self) -> Result<Self::Value, E> {
                Ok(UniqueValue(serde_json::Value::Null))
            }
            fn visit_unit<E: serde::de::Error>(self) -> Result<Self::Value, E> {
                Ok(UniqueValue(serde_json::Value::Null))
            }
            fn visit_seq<A: serde::de::SeqAccess<'de>>(
                self,
                mut sequence: A,
            ) -> Result<Self::Value, A::Error> {
                let mut values = Vec::new();
                while let Some(value) = sequence.next_element::<UniqueValue>()? {
                    values.push(value.0);
                }
                Ok(UniqueValue(values.into()))
            }
            fn visit_map<A: serde::de::MapAccess<'de>>(
                self,
                mut object: A,
            ) -> Result<Self::Value, A::Error> {
                let mut values = serde_json::Map::new();
                while let Some((name, value)) = object.next_entry::<String, UniqueValue>()? {
                    if values.insert(name.clone(), value.0).is_some() {
                        return Err(serde::de::Error::custom(format!(
                            "duplicate JSON key: {name}"
                        )));
                    }
                }
                Ok(UniqueValue(values.into()))
            }
        }
        deserializer.deserialize_any(Visitor)
    }
}

pub(crate) fn parse_unique_value(bytes: &[u8]) -> io::Result<serde_json::Value> {
    let unique: UniqueValue = serde_json::from_slice(bytes)?;
    Ok(unique.0)
}

fn parse<T: serde::de::DeserializeOwned>(bytes: &[u8]) -> io::Result<T> {
    serde_json::from_value(parse_unique_value(bytes)?).map_err(io::Error::other)
}

fn private_root(root: &Path) -> io::Result<()> {
    let metadata = root.symlink_metadata()?;
    if !metadata.is_dir()
        || metadata.uid() != unsafe { libc::geteuid() }
        || metadata.permissions().mode() & 0o077 != 0
    {
        return Err(invalid("capability proof root must be owner-private"));
    }
    Ok(())
}

fn environment_contract(values: &[EnvironmentRule], agent: &str) -> bool {
    if values.is_empty() {
        return false;
    }
    let mut prior = None;
    let mut home = false;
    let mut endpoint = false;
    let mut placeholder = false;
    for value in values {
        if value.name.is_empty()
            || !value
                .name
                .bytes()
                .all(|byte| byte.is_ascii_uppercase() || byte.is_ascii_digit() || byte == b'_')
            || prior.is_some_and(|prior| prior >= value.name.as_str())
            || !matches!(
                value.source.as_str(),
                "generated_private_directory"
                    | "fixed_nonsecret"
                    | "relay_endpoint"
                    | "fixed_placeholder"
            )
        {
            return false;
        }
        let fixed = matches!(
            value.source.as_str(),
            "fixed_nonsecret" | "fixed_placeholder"
        );
        if fixed != value.value_sha256.as_deref().is_some_and(digest)
            || (!fixed && value.value_sha256.is_some())
        {
            return false;
        }
        home |= value.name == "HOME" && value.source == "generated_private_directory";
        endpoint |= value.source == "relay_endpoint";
        placeholder |= value.source == "fixed_placeholder";
        prior = Some(value.name.as_str());
    }
    home && (endpoint || agent == "codex") && placeholder
}

fn system_configuration_contract(
    values: &[SystemPathRule],
    system_files: &SystemFiles,
) -> io::Result<bool> {
    if values.is_empty() {
        return Ok(false);
    }
    let mut prior: Option<&Path> = None;
    for value in values {
        if !value.path.is_absolute() || prior.is_some_and(|prior| prior >= value.path.as_path()) {
            return Ok(false);
        }
        match value.state.as_str() {
            "absent" => {
                if value.sha256.is_some() {
                    return Ok(false);
                }
                match system_files.path(&value.path).symlink_metadata() {
                    Err(error) if error.kind() == io::ErrorKind::NotFound => {}
                    _ => return Ok(false),
                }
            }
            "file" => {
                let expected = match value.sha256.as_deref().filter(|value| digest(value)) {
                    Some(value) => value,
                    None => return Ok(false),
                };
                if bounded(system_files.path(&value.path)).map(|bytes| sha256(&bytes))? != expected
                {
                    return Ok(false);
                }
            }
            _ => return Ok(false),
        }
        prior = Some(&value.path);
    }
    Ok(true)
}

fn current_username() -> io::Result<String> {
    let mut record = MaybeUninit::<libc::passwd>::uninit();
    let mut result = std::ptr::null_mut();
    let mut buffer = vec![0_u8; 16 * 1024];
    // SAFETY: record and buffer remain live for the call, their sizes are
    // exact, and result is checked before dereferencing the returned record.
    let status = unsafe {
        libc::getpwuid_r(
            libc::geteuid(),
            record.as_mut_ptr(),
            buffer.as_mut_ptr().cast(),
            buffer.len(),
            &mut result,
        )
    };
    if status != 0 || result.is_null() {
        return Err(invalid("current user identity is unavailable"));
    }
    // SAFETY: successful getpwuid_r returned a record backed by buffer and a
    // NUL-terminated pw_name for the lifetime of this function.
    let username = unsafe { CStr::from_ptr((*result).pw_name) }
        .to_str()
        .map_err(|_| invalid("current username is not UTF-8"))?;
    if username.is_empty() || username.contains('/') {
        return Err(invalid("current username is invalid"));
    }
    Ok(username.to_owned())
}

fn reviewed_system_paths_for(
    agent: &str,
    cli_version: &str,
    username: &str,
) -> io::Result<Vec<(PathBuf, String)>> {
    if username.is_empty() || username.contains('/') {
        return Err(invalid("current username is invalid"));
    }
    let bytes: &[u8] = match (agent, cli_version) {
        ("claude-code", "2.1.323 (Claude Code)") => {
            include_bytes!("../policies/claude-code-2.1.323-macos-system-paths.json")
        }
        ("codex", "codex-cli 0.169.0") => {
            include_bytes!("../policies/codex-0.169.0-macos-system-paths.json")
        }
        _ => return Err(invalid("unsupported reviewed system path contract")),
    };
    let contract = parse_unique_value(bytes)?;
    if contract["schema_version"] != 1
        || contract["agent"] != agent
        || contract["cli_version"] != cli_version
        || contract["os"] != "macos"
    {
        return Err(invalid("invalid reviewed system path contract"));
    }
    let values = contract["paths"]
        .as_array()
        .ok_or_else(|| invalid("reviewed system paths missing"))?;
    let mut paths = Vec::new();
    for value in values {
        let object = value
            .as_object()
            .filter(|object| object.len() == 2)
            .ok_or_else(|| invalid("invalid reviewed system path entry"))?;
        let path = match (
            object.get("path").and_then(Value::as_str),
            object.get("path_template").and_then(Value::as_str),
        ) {
            (Some(path), None) => PathBuf::from(path),
            (None, Some(template))
                if template.starts_with("/Library/Managed Preferences/{USER}/") =>
            {
                PathBuf::from(template.replace("{USER}", username))
            }
            _ => return Err(invalid("invalid reviewed system path selector")),
        };
        if !path.is_absolute() {
            return Err(invalid("reviewed system path is not absolute"));
        }
        let state = object
            .get("state")
            .and_then(Value::as_str)
            .filter(|state| matches!(*state, "absent" | "file"))
            .ok_or_else(|| invalid("invalid reviewed system path state"))?;
        paths.push((path, state.to_owned()));
    }
    paths.sort_by(|left, right| left.0.cmp(&right.0));
    for pair in paths.windows(2) {
        if pair[0].0 == pair[1].0 {
            return Err(invalid("reviewed system paths contain a duplicate"));
        }
    }
    Ok(paths)
}

pub(crate) fn reviewed_claude_system_paths() -> io::Result<Vec<(PathBuf, String)>> {
    reviewed_system_paths_for("claude-code", "2.1.323 (Claude Code)", &current_username()?)
}

pub(crate) fn reviewed_codex_system_paths() -> io::Result<Vec<(PathBuf, String)>> {
    reviewed_system_paths_for("codex", "codex-cli 0.169.0", &current_username()?)
}

fn reviewed_system_path_contract(profile: &LauncherProfile) -> io::Result<bool> {
    let expected = match profile.agent.as_str() {
        "claude-code" => reviewed_claude_system_paths()?,
        "codex" => reviewed_codex_system_paths()?,
        _ => return Ok(false),
    };
    Ok(profile.system_configuration.len() == expected.len()
        && profile
            .system_configuration
            .iter()
            .zip(expected)
            .all(|(actual, (path, state))| actual.path == path && actual.state == state))
}

fn exact_facts<'a>(
    value: &'a Value,
    names: &[&str],
) -> io::Result<&'a serde_json::Map<String, Value>> {
    let values = value
        .as_object()
        .ok_or_else(|| invalid("acceptance facts are not an object"))?;
    if values.keys().map(String::as_str).collect::<BTreeSet<_>>()
        != names.iter().copied().collect::<BTreeSet<_>>()
    {
        return Err(invalid("acceptance facts do not match the check contract"));
    }
    Ok(values)
}

fn positive(value: Option<&Value>) -> bool {
    value.and_then(Value::as_u64).is_some_and(|value| value > 0)
}

struct EvidenceBinding<'a> {
    agent: &'a str,
    profile_sha256: &'a str,
    request_policy_sha256: &'a str,
    runner_sha256: &'a str,
    probe_id: &'a str,
    probe_nonce_sha256: &'a str,
    acceptance_request_count: u64,
    production_request_budget: u64,
}

fn semantic_evidence(check: &str, bytes: &[u8], binding: &EvidenceBinding<'_>) -> io::Result<()> {
    let evidence: AcceptanceEvidence = parse(bytes)?;
    if evidence.schema_version != 1
        || evidence.check != check
        || evidence.profile_sha256 != binding.profile_sha256
        || evidence.runner_sha256 != binding.runner_sha256
        || evidence.probe_id != binding.probe_id
        || evidence.probe_nonce_sha256 != binding.probe_nonce_sha256
        || evidence.started_ns == 0
        || evidence.finished_ns < evidence.started_ns
    {
        return Err(invalid("acceptance evidence binding mismatch"));
    }
    let valid = match check {
        "allowed_mcp_succeeded" => {
            let facts = exact_facts(&evidence.facts, &["attempts", "successes", "audit_bound"])?;
            positive(facts.get("attempts"))
                && facts["attempts"] == facts["successes"]
                && facts["audit_bound"] == true
        }
        "control_socket_unavailable" => {
            let facts = exact_facts(
                &evidence.facts,
                &[
                    "attempts",
                    "rejections",
                    "bypass_events",
                    "positive_control_attempts",
                    "positive_control_connections",
                ],
            )?;
            positive(facts.get("attempts"))
                && facts["attempts"] == facts["rejections"]
                && facts["bypass_events"] == 0
                && facts["positive_control_attempts"] == 1
                && facts["positive_control_connections"] == 1
        }
        "hmac_unavailable" | "host_tools_rejected" => {
            let facts = exact_facts(
                &evidence.facts,
                &["attempts", "rejections", "bypass_events"],
            )?;
            positive(facts.get("attempts"))
                && facts["attempts"] == facts["rejections"]
                && facts["bypass_events"] == 0
        }
        "host_canary_read_denied" => {
            let facts = exact_facts(
                &evidence.facts,
                &["attempts", "rejections", "before_sha256", "after_sha256"],
            )?;
            positive(facts.get("attempts"))
                && facts["attempts"] == facts["rejections"]
                && facts["before_sha256"] == facts["after_sha256"]
                && facts["before_sha256"].as_str().is_some_and(digest)
        }
        "host_canary_write_denied" => {
            let facts = exact_facts(&evidence.facts, &["attempts", "rejections", "created"])?;
            positive(facts.get("attempts"))
                && facts["attempts"] == facts["rejections"]
                && facts["created"] == false
        }
        "mcp_child_env_sanitized" => {
            let facts = exact_facts(&evidence.facts, &["samples", "violations"])?;
            positive(facts.get("samples")) && facts["violations"] == 0
        }
        "provider_request_policy" => {
            let facts = exact_facts(
                &evidence.facts,
                &[
                    "requests",
                    "rejected",
                    "policy_sha256",
                    "negative_probes",
                    "negative_rejections",
                    "upstream_bypass_events",
                    "acceptance_request_count",
                    "production_request_budget",
                ],
            )?;
            positive(facts.get("requests"))
                && facts["requests"] == binding.acceptance_request_count
                && facts["rejected"] == 0
                && facts["policy_sha256"] == binding.request_policy_sha256
                && positive(facts.get("negative_probes"))
                && facts["negative_probes"] == facts["negative_rejections"]
                && facts["upstream_bypass_events"] == 0
                && facts["acceptance_request_count"] == binding.acceptance_request_count
                && facts["production_request_budget"] == binding.production_request_budget
        }
        "tool_catalog_exact" => {
            let names = if binding.agent == "codex" {
                &[
                    "requests",
                    "expected_sha256",
                    "observed_sha256",
                    "framework_exception_verified",
                    "mcp_policy_rejections",
                    "request_user_input_response_ns",
                ][..]
            } else {
                &["requests", "expected_sha256", "observed_sha256"][..]
            };
            let facts = exact_facts(&evidence.facts, names)?;
            let framework_valid = binding.agent != "codex"
                || (facts["framework_exception_verified"] == true
                    && facts["mcp_policy_rejections"] == 5
                    && facts["request_user_input_response_ns"]
                        .as_u64()
                        .is_some_and(|value| value <= 5_000_000_000));
            positive(facts.get("requests"))
                && facts["expected_sha256"] == facts["observed_sha256"]
                && facts["expected_sha256"].as_str().is_some_and(digest)
                && framework_valid
        }
        _ => false,
    };
    if !valid {
        return Err(invalid("acceptance evidence did not establish the check"));
    }
    Ok(())
}

/// Verify only the envelope, file integrity, and static profile contract.
/// This does not establish that any capability check was meaningfully run.
fn load_envelope_inner(
    root: &Path,
    verify_live_code: bool,
    system_files: &SystemFiles,
) -> io::Result<VerifiedEnvelope> {
    private_root(root)?;
    private_root(&root.join("evidence"))?;
    let profile_bytes = bounded(&root.join("launcher-profile.json"))?;
    let profile_sha256 = sha256(&profile_bytes);
    let profile: LauncherProfile = parse(&profile_bytes)?;
    let proof_bytes = bounded(&root.join("capability-proof.json"))?;
    let proof_sha256 = sha256(&proof_bytes);
    let proof: Proof = parse(&proof_bytes)?;
    let current_runner_sha256 = host_io::digest(&std::env::current_exe()?)?;
    if proof.schema_version != 1
        || profile.schema_version != 1
        || !identifier(&proof.proof_id)
        || proof.created_ns == 0
        || !digest(&proof.profile_sha256)
        || proof.profile_sha256 != profile_sha256
        || proof.runner_sha256 != current_runner_sha256
        || !identifier(&proof.probe_id)
        || !digest(&proof.probe_nonce_sha256)
    {
        return Err(invalid("invalid capability proof identity"));
    }
    if !matches!(profile.agent.as_str(), "codex" | "claude-code")
        || profile.model.is_empty()
        || profile.cli_version.is_empty()
        || !matches!(
            profile.provider_protocol.as_str(),
            "openai-responses" | "anthropic-messages"
        )
        || !matches!(
            (
                profile.agent.as_str(),
                profile.provider_protocol.as_str(),
                profile.upstream_base_url.as_str()
            ),
            ("codex", "openai-responses", "https://api.openai.com/v1/")
                | (
                    "claude-code",
                    "anthropic-messages",
                    "https://api.anthropic.com/"
                )
        )
        || profile.proof_upstream_kind != "local_deterministic_stub_through_relay"
        || profile.allowed_runtime_variance != ["relay_authentication_value"]
        || !digest(&profile.request_policy_sha256)
        || !(1..=profile.production_request_budget).contains(&profile.acceptance_request_count)
        || !(1..=1000).contains(&profile.production_request_budget)
        || profile.argument_template.is_empty()
        || !environment_contract(&profile.environment, &profile.agent)
        || profile.home_policy != "empty_owner_private"
        || profile.cwd_policy != "empty_owner_private"
        || profile.prompt_policy != "tempest_generated_only"
        || profile.real_authentication_owner != "model_api_relay_only"
        || !reviewed_system_path_contract(&profile)?
        || !system_configuration_contract(&profile.system_configuration, system_files)?
    {
        return Err(invalid("invalid launcher profile contract"));
    }
    let expected_checks: BTreeSet<_> = REQUIRED_CHECKS
        .iter()
        .map(|value| value.to_string())
        .collect();
    if proof.checks.keys().cloned().collect::<BTreeSet<_>>() != expected_checks {
        return Err(invalid("capability proof checks are incomplete"));
    }
    let mut evidence = BTreeMap::new();
    for artifact in &proof.evidence {
        if !identifier(&artifact.name)
            || !digest(&artifact.sha256)
            || artifact.bytes > LIMIT
            || evidence.insert(artifact.name.clone(), artifact).is_some()
        {
            return Err(invalid("invalid proof evidence manifest"));
        }
        let bytes = bounded(&root.join("evidence").join(&artifact.name))?;
        if bytes.len() as u64 != artifact.bytes || sha256(&bytes) != artifact.sha256 {
            return Err(invalid("proof evidence digest mismatch"));
        }
    }
    let mut used_evidence = BTreeSet::new();
    let evidence_binding = EvidenceBinding {
        agent: &profile.agent,
        profile_sha256: &profile_sha256,
        request_policy_sha256: &profile.request_policy_sha256,
        runner_sha256: &proof.runner_sha256,
        probe_id: &proof.probe_id,
        probe_nonce_sha256: &proof.probe_nonce_sha256,
        acceptance_request_count: profile.acceptance_request_count,
        production_request_budget: profile.production_request_budget,
    };
    for (name, check) in &proof.checks {
        if !check.performed
            || !check.passed
            || check.profile_sha256 != profile_sha256
            || check.evidence.len() != 1
            || check
                .evidence
                .iter()
                .any(|name| !evidence.contains_key(name))
            || !used_evidence.insert(check.evidence[0].clone())
        {
            return Err(invalid("capability acceptance check not established"));
        }
        semantic_evidence(
            name,
            &bounded(&root.join("evidence").join(&check.evidence[0]))?,
            &evidence_binding,
        )?;
    }
    let mut roles = BTreeSet::new();
    for artifact in &profile.code_closure {
        if !identifier(&artifact.role)
            || !roles.insert(artifact.role.clone())
            || !artifact.path.is_absolute()
            || !digest(&artifact.sha256)
            || (verify_live_code
                && (!artifact.path.symlink_metadata()?.is_file()
                    || artifact.path.canonicalize()? != artifact.path
                    || host_io::digest(&artifact.path)? != artifact.sha256))
        {
            return Err(invalid("launcher code closure mismatch"));
        }
    }
    for required in ["agent_executable", "mcp_bridge", "model_api_relay"] {
        if !roles.contains(required) {
            return Err(invalid("launcher code closure is incomplete"));
        }
    }
    Ok(VerifiedEnvelope {
        proof_id: proof.proof_id,
        profile_sha256,
        profile,
        proof_sha256,
        created_ns: proof.created_ns,
        runner_sha256: proof.runner_sha256,
        probe_id: proof.probe_id,
        probe_nonce_sha256: proof.probe_nonce_sha256,
    })
}

pub fn load_envelope(root: &Path) -> io::Result<VerifiedEnvelope> {
    load_envelope_inner(root, true, &SystemFiles::default())
}

